// Helper to get nested value from SurveyData chapter
export function getNestedField(chapterObj: any, path: string): string {
  if (!chapterObj) return "";
  const parts = path.split(".");
  let cur = chapterObj;
  for (const p of parts) {
    if (cur == null) return "";
    cur = cur[p];
  }
  return typeof cur === "string" ? cur : "";
}

// Helper to set nested value immutably on SurveyData
export function setNestedField(data: any, chapterKey: string, path: string, val: string): any {
  const parts = path.split(".");
  const nextCh = { ...(data[chapterKey] || {}) };
  if (parts.length === 1) {
    nextCh[parts[0]] = val;
  } else if (parts.length === 2) {
    nextCh[parts[0]] = { ...(nextCh[parts[0]] || {}), [parts[1]]: val };
  }
  return { ...data, [chapterKey]: nextCh };
}
